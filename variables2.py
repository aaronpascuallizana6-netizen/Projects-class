# Se crea una variable con el valor 1.
a = 1
# Se suma 1 al valor de a y se guarda el resultado en b.
b = a + 1
# Se muestra el valor de b.
print(b)

# Se vuelve a asignar el valor 1 a a.
a = 1
# Se muestra el valor actual de a.
print(a)
# Se incrementa a en 1.
a += 1
# Se muestra el nuevo valor de a.
print(a)